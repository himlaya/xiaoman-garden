"""本机使用 SQLite；配置 DATABASE_URL 后使用云端 PostgreSQL。"""

from __future__ import annotations

import sqlite3
from datetime import datetime, timezone
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT NOT NULL UNIQUE COLLATE NOCASE,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL,
    last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS saves (
    user_id INTEGER PRIMARY KEY,
    payload TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS market_listings (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    seller_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    item_json TEXT NOT NULL,
    price INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TEXT NOT NULL,
    buyer_id INTEGER,
    sold_at TEXT,
    FOREIGN KEY (seller_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (buyer_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS market_active_item
    ON market_listings(item_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS market_active_listings
    ON market_listings(status, created_at);
"""


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def is_postgres(database: str | Path) -> bool:
    return str(database).startswith(("postgres://", "postgresql://"))


class PostgresConnection:
    """让现有参数化 SQL 共用一套接口；数据始终通过 bind 传入。"""

    def __init__(self, database: str):
        import psycopg
        from psycopg.rows import dict_row

        self._integrity_error = psycopg.IntegrityError
        self.connection = psycopg.connect(
            database, autocommit=True, row_factory=dict_row,
            connect_timeout=15, prepare_threshold=None,
        )

    def execute(self, sql, parameters=()):
        try:
            # 这里只接受项目内固定 SQL，不拼接用户提供的 SQL。
            return self.connection.execute(sql.replace("?", "%s"), parameters or None)
        except self._integrity_error as error:
            raise sqlite3.IntegrityError("database constraint violation") from error

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def begin_write(connection):
    """串行执行存档与市场写入，避免两个买家重复成交或读改写丢更新。"""
    if isinstance(connection, PostgresConnection):
        connection.execute("BEGIN")
        connection.execute("LOCK TABLE saves, market_listings IN SHARE ROW EXCLUSIVE MODE")
    else:
        connection.execute("BEGIN IMMEDIATE")


def connect_db(database: str | Path):
    if is_postgres(database):
        return PostgresConnection(str(database))
    if "://" in str(database):
        raise ValueError("DATABASE_URL 必须是 postgresql:// 或 postgres:// 连接地址")
    path = Path(database)
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")
    return connection


def init_db(database: str | Path) -> None:
    connection = connect_db(database)
    try:
        if is_postgres(database):
            schema = SCHEMA.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            ).replace("username TEXT NOT NULL UNIQUE COLLATE NOCASE", "username TEXT NOT NULL")
            # 原子建表；同一数据库重复启动不会删除数据。
            connection.execute("BEGIN")
            connection.execute(schema)
            connection.execute("CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username))")
            connection.execute("ALTER TABLE saves ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 0")
        else:
            connection.executescript(SCHEMA)
            columns = {row["name"] for row in connection.execute("PRAGMA table_info(saves)")}
            if "revision" not in columns:
                connection.execute("ALTER TABLE saves ADD COLUMN revision INTEGER NOT NULL DEFAULT 0")
        connection.commit()
    finally:
        connection.close()
